<p>
    The <strong>Prism Student Disciplinary Case Management System (PRISM)</strong> is operated by the
    NU Clark Student Discipline Office to record, process, and manage disciplinary cases, University
    Service, guidance referrals, and related records. This notice explains what personal data PRISM
    collects, why it is processed, and your rights under the <strong>Data Privacy Act of 2012 (RA 10173)</strong>.
    By continuing, you acknowledge that your information will be handled responsibly and in accordance
    with this notice.
</p>

<h2>Personal Data We Collect</h2>
<ul>
    <li><strong>Identity and contact details:</strong> name, student/employee ID, email address, contact number, and profile photo.</li>
    <li><strong>Case and disciplinary records:</strong> incident reports, violation slips, written explanations, case notices, hearing notes, sanctions, appeals, and University Service assignments and attendance.</li>
    <li><strong>Guidance and counseling records:</strong> counseling referrals and session outcomes, accessible only to authorized guidance personnel.</li>
    <li><strong>Uploaded evidence:</strong> attachments submitted with reports, explanations, or appeals (e.g. photos, documents).</li>
    <li><strong>Risk and monitoring data:</strong> behavioral risk scores and intervention records used to identify students who may need support.</li>
    <li><strong>System and access logs:</strong> login activity, audit trails, and device/browser information used to secure the system and trace access to sensitive records.</li>
</ul>

<h2>Why We Process Your Data</h2>
<p>PRISM processes personal data for legitimate disciplinary and administrative purposes, including:</p>
<ul>
    <li>Recording, investigating, and resolving disciplinary cases in line with the Student Handbook;</li>
    <li>Issuing notices, tracking explanations, sanctions, appeals, and University Service compliance;</li>
    <li>Coordinating guidance and counseling support for students who need it;</li>
    <li>Generating reports and analytics for the Discipline Office and university administration;</li>
    <li>Maintaining audit logs to secure records and account for access to confidential data.</li>
</ul>

<h2>How We Protect Your Data</h2>
<ul>
    <li><strong>Access control:</strong> only authorized roles (e.g. Discipline Officers, Coordinators, Guidance Officers) can view records relevant to their function.</li>
    <li><strong>Private storage:</strong> uploaded attachments and evidence are kept in private storage, not publicly accessible.</li>
    <li><strong>Audit trails:</strong> logins, updates, overrides, and report generation are logged for accountability.</li>
    <li><strong>Encrypted secrets:</strong> sensitive generated credentials (e.g. attendance verification codes) are encrypted at rest.</li>
    <li><strong>Retention:</strong> case records and attachments are retained according to the Discipline Office's official retention policy and are not deleted without an approved disposal process.</li>
</ul>

<h2>Who We Share It With</h2>
<p>
    Disciplinary information may be shared internally with the Discipline Office, Guidance Office, and
    relevant academic units strictly for case handling, guidance support, and reporting to university
    administration. PRISM does not sell or share your personal data with third parties for marketing
    purposes.
</p>

