<?php

declare(strict_types=1);

namespace App\Services;

use App\Models\ScheduledReport;
use App\Models\User;
use Barryvdh\DomPDF\Facade\Pdf;
use Carbon\CarbonImmutable;
use Illuminate\Support\Facades\Storage;
use PhpOffice\PhpSpreadsheet\Cell\Coordinate;
use PhpOffice\PhpSpreadsheet\Cell\DataType;
use PhpOffice\PhpSpreadsheet\Shared\Date as ExcelDate;
use PhpOffice\PhpSpreadsheet\Spreadsheet;
use PhpOffice\PhpSpreadsheet\Style\Alignment;
use PhpOffice\PhpSpreadsheet\Style\Border;
use PhpOffice\PhpSpreadsheet\Style\Color;
use PhpOffice\PhpSpreadsheet\Style\Fill;
use PhpOffice\PhpSpreadsheet\Worksheet\PageSetup;
use PhpOffice\PhpSpreadsheet\Worksheet\Worksheet;
use PhpOffice\PhpSpreadsheet\Writer\Xlsx;

/**
 * Builds the CSV and PDF exports for disciplinary and risk reports,
 * rendering the PDF path through reports.exports.structured-pdf via
 * DomPDF (Pdf::loadView, not the view() helper — worth knowing if you're
 * grepping for where a view is used).
 */
final class ReportExportService
{
    public function __construct(private readonly ReportDocumentBuilder $documents) {}

    public function generate(string $type, array $filters, ?int $generatedBy, string $format = 'xlsx'): ScheduledReport
    {
        if (! in_array($format, ['xlsx', 'pdf'], true)) {
            throw new \InvalidArgumentException('Unsupported report export format.');
        }

        $document = $this->documents->build($type, $filters, $this->reportScopeUser($generatedBy));
        $contents = $format === 'pdf'
            ? $this->pdf($document, $generatedBy)
            : $this->excel($document, $generatedBy);
        $stamp = now()->format('Ymd_His_u');
        $path = "reports/{$type}_{$stamp}.{$format}";

        if (! Storage::disk('local')->put($path, $contents)) {
            throw new \RuntimeException('The report file could not be written to storage.');
        }

        return ScheduledReport::create([
            'report_type' => $type,
            'period_start' => $document['period_start'],
            'period_end' => $document['period_end'],
            'generated_by' => $generatedBy,
            'file_path' => $path,
            'generated_at' => now(),
            'created_at' => now(),
        ]);
    }

    public function pdfPreview(string $type, array $filters, ?int $generatedBy): string
    {
        return $this->pdf(
            $this->documents->build($type, $filters, $this->reportScopeUser($generatedBy)),
            $generatedBy,
        );
    }

    /**
     * The generating user, but only when their reports are department-scoped;
     * otherwise null so the export stays institution-wide.
     */
    private function reportScopeUser(?int $generatedBy): ?User
    {
        if ($generatedBy === null) {
            return null;
        }

        $user = User::find($generatedBy);

        return $user?->scopesReportsByDepartment() ? $user : null;
    }

    private function excel(array $document, ?int $generatedBy): string
    {
        $generator = $generatedBy ? User::find($generatedBy) : null;
        $spreadsheet = new Spreadsheet;
        $spreadsheet->getProperties()
            ->setCreator($generator?->list_name ?? 'PRISM System')
            ->setCompany('National University Clark')
            ->setTitle($document['title'])
            ->setSubject('Student Discipline Office report')
            ->setDescription('Generated by PRISM from stored report data.');

        $summarySheet = $spreadsheet->getActiveSheet();
        $summarySheet->setTitle('Report Summary');
        $this->buildSummarySheet($summarySheet, $document, $generator?->list_name ?? 'System scheduler');

        $usedNames = ['Report Summary'];
        foreach ($document['sections'] as $section) {
            $sheet = $spreadsheet->createSheet();
            $sheetName = $this->uniqueSheetName($section['title'], $usedNames);
            $usedNames[] = $sheetName;
            $sheet->setTitle($sheetName);
            $this->buildDataSheet($sheet, $document, $section);
        }

        $spreadsheet->setActiveSheetIndex(0);
        $stream = fopen('php://temp', 'w+');
        if ($stream === false) {
            $spreadsheet->disconnectWorksheets();
            throw new \RuntimeException('The Excel export stream could not be created.');
        }

        (new Xlsx($spreadsheet))->save($stream);

        rewind($stream);
        $contents = stream_get_contents($stream);
        fclose($stream);
        $spreadsheet->disconnectWorksheets();

        if ($contents === false) {
            throw new \RuntimeException('The Excel export could not be read.');
        }

        return $contents;
    }

    private function buildSummarySheet(Worksheet $sheet, array $document, string $generatedBy): void
    {
        $sheet->setShowGridlines(false);
        $sheet->getSheetView()->setZoomScale(90);
        $sheet->mergeCells('A1:C1');
        $sheet->setCellValue('A1', 'NATIONAL UNIVERSITY CLARK');
        $sheet->mergeCells('A2:C2');
        $sheet->setCellValue('A2', 'Student Discipline Office · PRISM');
        $sheet->mergeCells('A4:F4');
        $sheet->setCellValue('A4', $document['title']);
        $sheet->mergeCells('A5:F5');
        $sheet->setCellValue('A5', $document['period_start'].' to '.$document['period_end']);

        $sheet->getStyle('A1:C1')->applyFromArray([
            'font' => ['bold' => true, 'size' => 15, 'color' => ['rgb' => 'FFFFFF']],
            'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => '1E3276']],
            'alignment' => ['vertical' => Alignment::VERTICAL_CENTER],
        ]);
        $sheet->getStyle('A2:C2')->applyFromArray([
            'font' => ['size' => 9, 'color' => ['rgb' => 'DCE7FF']],
            'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => '1E3276']],
        ]);
        $sheet->getStyle('A4:F4')->applyFromArray([
            'font' => ['bold' => true, 'size' => 20, 'color' => ['rgb' => '101828']],
        ]);
        $sheet->getStyle('A5:F5')->getFont()->setColor(new Color('667085'));
        $sheet->getRowDimension(1)->setRowHeight(26);
        $sheet->getRowDimension(2)->setRowHeight(20);
        $sheet->getRowDimension(4)->setRowHeight(30);

        $metadata = [
            ['Generated At', now()->format('Y-m-d H:i:s')],
            ['Generated By', $generatedBy],
            ...$document['filters'],
        ];
        $row = 7;
        foreach ($metadata as [$label, $value]) {
            $sheet->setCellValue("A{$row}", $label);
            $sheet->mergeCells("B{$row}:C{$row}");
            $this->setTypedCell($sheet, "B{$row}", $value);
            $sheet->getStyle("B{$row}")->getAlignment()->setHorizontal(Alignment::HORIZONTAL_CENTER);
            $row++;
        }
        $metadataEnd = $row - 1;
        $sheet->getStyle("A7:A{$metadataEnd}")->applyFromArray([
            'font' => ['bold' => true, 'color' => ['rgb' => '526078']],
            'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => 'F3F6FB']],
        ]);
        $sheet->getStyle("A7:C{$metadataEnd}")->getBorders()->getBottom()->setBorderStyle(Border::BORDER_HAIR);

        $row += 2;
        $sheet->mergeCells("A{$row}:C{$row}");
        $sheet->setCellValue("A{$row}", 'EXECUTIVE SUMMARY');
        $sheet->getStyle("A{$row}:C{$row}")->applyFromArray([
            'font' => ['bold' => true, 'size' => 11, 'color' => ['rgb' => '203C91']],
            'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => 'EDF3FF']],
        ]);
        $row += 2;

        foreach ($document['summary'] as [$label, $value]) {
            $sheet->setCellValue("A{$row}", $label);
            $sheet->mergeCells("B{$row}:C{$row}");
            $this->setTypedCell($sheet, "B{$row}", $value);
            $this->centerIfNumericOrDate($sheet, "B{$row}", $value);
            $sheet->getStyle("A{$row}")->applyFromArray([
                'font' => ['bold' => true, 'size' => 9, 'color' => ['rgb' => '667085']],
                'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => 'F8FAFD']],
            ]);
            $sheet->getStyle("B{$row}")->applyFromArray([
                'font' => ['bold' => true, 'size' => 12, 'color' => ['rgb' => '172554']],
            ]);
            $sheet->getStyle("A{$row}:C{$row}")->applyFromArray([
                'borders' => ['allBorders' => ['borderStyle' => Border::BORDER_THIN, 'color' => ['rgb' => 'DCE5F1']]],
            ]);
            $sheet->getRowDimension($row)->setRowHeight(28);
            $row++;
        }

        foreach (range('A', 'F') as $column) {
            $sheet->getColumnDimension($column)->setWidth($column === 'A' ? 22 : 18);
        }
        $sheet->freezePane('A7');
        $this->configurePrint($sheet, 6);
    }

    private function buildDataSheet(Worksheet $sheet, array $document, array $section): void
    {
        $sheet->setShowGridlines(false);
        $sheet->getSheetView()->setZoomScale(85);
        $columnCount = max(1, count($section['headers']));
        $lastColumn = Coordinate::stringFromColumnIndex($columnCount);

        $sheet->mergeCells("A1:{$lastColumn}1");
        $sheet->setCellValue('A1', $section['title']);
        $sheet->mergeCells("A2:{$lastColumn}2");
        $sheet->setCellValue('A2', $document['title'].' · '.$document['period_start'].' to '.$document['period_end']);
        $sheet->getStyle("A1:{$lastColumn}1")->applyFromArray([
            'font' => ['bold' => true, 'size' => 15, 'color' => ['rgb' => 'FFFFFF']],
            'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => '1E3276']],
            'alignment' => ['vertical' => Alignment::VERTICAL_CENTER],
        ]);
        $sheet->getStyle("A2:{$lastColumn}2")->applyFromArray([
            'font' => ['size' => 8, 'color' => ['rgb' => 'DCE7FF']],
            'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => '1E3276']],
        ]);
        $sheet->getRowDimension(1)->setRowHeight(25);
        $sheet->getRowDimension(2)->setRowHeight(18);

        $headerRow = 4;
        foreach ($section['headers'] as $index => $header) {
            $column = Coordinate::stringFromColumnIndex($index + 1);
            $sheet->setCellValue("{$column}{$headerRow}", $header);
        }
        $sheet->getStyle("A{$headerRow}:{$lastColumn}{$headerRow}")->applyFromArray([
            'font' => ['bold' => true, 'color' => ['rgb' => 'FFFFFF']],
            'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => '3156C7']],
            'alignment' => ['vertical' => Alignment::VERTICAL_CENTER, 'wrapText' => true],
            'borders' => ['allBorders' => ['borderStyle' => Border::BORDER_THIN, 'color' => ['rgb' => '27479E']]],
        ]);
        $sheet->getRowDimension($headerRow)->setRowHeight(28);

        $rowNumber = $headerRow + 1;
        foreach ($section['rows'] as $rowIndex => $row) {
            foreach ($section['headers'] as $columnIndex => $header) {
                $column = Coordinate::stringFromColumnIndex($columnIndex + 1);
                $this->setTypedCell($sheet, "{$column}{$rowNumber}", $row[$columnIndex] ?? '');
            }
            if ($rowIndex % 2 === 1) {
                $sheet->getStyle("A{$rowNumber}:{$lastColumn}{$rowNumber}")
                    ->getFill()->setFillType(Fill::FILL_SOLID)->getStartColor()->setRGB('F5F8FE');
            }
            $rowNumber++;
        }

        $lastDataRow = max($headerRow, $rowNumber - 1);
        $sheet->getStyle("A{$headerRow}:{$lastColumn}{$lastDataRow}")->applyFromArray([
            'alignment' => ['vertical' => Alignment::VERTICAL_TOP, 'wrapText' => true],
            'borders' => ['allBorders' => ['borderStyle' => Border::BORDER_THIN, 'color' => ['rgb' => 'DCE3EC']]],
        ]);
        if ($section['rows'] !== []) {
            $sheet->setAutoFilter("A{$headerRow}:{$lastColumn}{$lastDataRow}");
        }
        $sheet->freezePane('A5');

        foreach ($section['headers'] as $index => $header) {
            $column = Coordinate::stringFromColumnIndex($index + 1);
            $values = array_map(fn (array $row) => (string) ($row[$index] ?? ''), $section['rows']);
            $length = max([mb_strlen((string) $header), ...array_map('mb_strlen', $values)]);
            $sheet->getColumnDimension($column)->setWidth(min(45, max(12, $length + 2)));
        }

        $this->configurePrint($sheet, $columnCount);
    }

    private function setTypedCell(Worksheet $sheet, string $coordinate, mixed $value): void
    {
        if (is_int($value) || is_float($value)) {
            $sheet->setCellValueExplicit($coordinate, $value, DataType::TYPE_NUMERIC);

            return;
        }

        $text = trim((string) ($value ?? ''));
        if (preg_match('/^\d{4}-\d{2}-\d{2}$/', $text) === 1) {
            $sheet->setCellValue($coordinate, ExcelDate::PHPToExcel(CarbonImmutable::parse($text)->startOfDay()));
            $sheet->getStyle($coordinate)->getNumberFormat()->setFormatCode('mmm d, yyyy');

            return;
        }
        if (preg_match('/^\d{4}-\d{2}-\d{2} \d{2}:\d{2}(?::\d{2})?$/', $text) === 1) {
            $sheet->setCellValue($coordinate, ExcelDate::PHPToExcel(CarbonImmutable::parse($text)));
            $sheet->getStyle($coordinate)->getNumberFormat()->setFormatCode('mmm d, yyyy h:mm AM/PM');

            return;
        }

        $sheet->setCellValueExplicit($coordinate, $text, DataType::TYPE_STRING);
    }

    private function centerIfNumericOrDate(Worksheet $sheet, string $coordinate, mixed $rawValue): void
    {
        $isNumericCell = $sheet->getCell($coordinate)->getDataType() === DataType::TYPE_NUMERIC;
        $isNumericLikeText = is_string($rawValue) && preg_match('/^-?\d+(\.\d+)?%?$/', trim($rawValue)) === 1;

        if ($isNumericCell || $isNumericLikeText) {
            $sheet->getStyle($coordinate)->getAlignment()->setHorizontal(Alignment::HORIZONTAL_CENTER);
        }
    }

    private function configurePrint(Worksheet $sheet, int $columnCount): void
    {
        $sheet->getPageSetup()
            ->setOrientation($columnCount > 7
                ? PageSetup::ORIENTATION_LANDSCAPE
                : PageSetup::ORIENTATION_PORTRAIT)
            ->setPaperSize(PageSetup::PAPERSIZE_A4)
            ->setFitToWidth(1)
            ->setFitToHeight(0);
        $sheet->getPageMargins()->setTop(0.5)->setRight(0.35)->setBottom(0.55)->setLeft(0.35);
        $sheet->getHeaderFooter()
            ->setOddHeader('&L&BNational University Clark&RPRISM Report')
            ->setOddFooter('&LConfidential - Internal Use Only&RPage &P of &N');
    }

    private function uniqueSheetName(string $title, array $usedNames): string
    {
        $base = trim(str_replace(['\\', '/', '?', '*', '[', ']', ':'], '', $title));
        $base = mb_substr($base !== '' ? $base : 'Report Data', 0, 31);
        $candidate = $base;
        $suffix = 2;

        while (in_array($candidate, $usedNames, true)) {
            $tail = " ({$suffix})";
            $candidate = mb_substr($base, 0, 31 - mb_strlen($tail)).$tail;
            $suffix++;
        }

        return $candidate;
    }

    private function pdf(array $document, ?int $generatedBy): string
    {
        $generator = $generatedBy ? User::find($generatedBy) : null;
        $widestTable = collect($document['sections'])->max(fn (array $section) => count($section['headers'])) ?? 0;
        $orientation = $widestTable > 7 ? 'landscape' : 'portrait';

        return Pdf::loadView('reports.exports.structured-pdf', [
            'report' => $document,
            'generatedBy' => $generator?->list_name ?? 'System scheduler',
            'generatedAt' => now(),
            'orientation' => $orientation,
        ])
            ->setPaper('a4', $orientation)
            ->setOption('isPhpEnabled', true)
            ->setOption('isRemoteEnabled', false)
            ->output();
    }
}
